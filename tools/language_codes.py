"""Generate UI display metadata without changing stored or wire language identities."""

import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src-python/models/transcription/transcription_languages.py"
OUTPUT = ROOT / "src-ui/logics/common/languageCodes.js"


def language_codes():
    tree = ast.parse(SOURCE.read_text(encoding="utf-8"))
    table = next(ast.literal_eval(node.value) for node in tree.body
                 if isinstance(node, ast.Assign)
                 and any(isinstance(target, ast.Name) and target.id == "transcription_lang"
                         for target in node.targets))
    return {language: {country: codes.get("Google") for country, codes in countries.items()}
            for language, countries in table.items()}


def render():
    return ("// Generated by python tools/language_codes.py --write; do not edit.\n"
            "// Google tags from models/transcription/transcription_languages.py.\n"
            "export const languageCodes = "
            + json.dumps(language_codes(), ensure_ascii=False, indent=4) + ";\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Update the generated UI table")
    args = parser.parse_args()
    expected = render()
    if args.write:
        OUTPUT.write_text(expected, encoding="utf-8")
        return 0
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
        print("UI language tags are stale; run python tools/language_codes.py --write")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
